"""Prints a balance report for main attacks, play styles and Pokémon from the JSON data.

    python3 tools/balance_report.py           # per-style summary + outliers
    python3 tools/balance_report.py --all     # every main attack

Damage figures are raw move power per second before attack/defense, STAB and
type, so they compare like with like. Main attacks are generated by
tools/build_roster.py; run this after changing its numbers to spot outliers.
"""
import json, math, os, statistics, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data")
moves = {}
for f in sorted(os.listdir(os.path.join(ROOT, "moves"))):
    if f.endswith(".json"):
        moves.update({k: v for k, v in json.load(open(os.path.join(ROOT, "moves", f))).items() if not k.startswith("_")})
rules = json.load(open(os.path.join(ROOT, "rules.json")))
species = {f[:-5]: json.load(open(os.path.join(ROOT, "brawlers", f)))
           for f in sorted(os.listdir(os.path.join(ROOT, "brawlers")))}
HP_MULT = rules.get("hp_multiplier", 1.0)


def hit_factor(m):
    """Rough share of a volley that lands on one target."""
    f = 1.0
    if m.get("count", 1) > 1:
        f *= 0.75 if m.get("spread", 0) <= 15 else 0.55
    return f


def move_dps(m):
    """Sustained damage per second against one target if every attack lands."""
    kind = m["kind"]
    if kind == "stream":
        return m["power"] * m["tank"] / (m["tank"] + m["reload"])
    if m.get("linger"):
        return m["power"] * m["linger"] / m["reload"]  # power is per second in the zone
    per_hit = m["power"] * m.get("count", 1) * m.get("burst_count", 1) * hit_factor(m)
    if m.get("returns"):
        per_hit *= 1.6
    if m.get("chain"):
        per_hit *= 1.0 + 0.4 * m["chain"]
    return per_hit / m.get("reload", 1.0)


def reach(m):
    if m["kind"] == "dash":
        return m["dash_distance"]
    return m.get("range", 0) + m.get("explode_radius", 0)


def mains_of(sid):
    s = species[sid]
    while "moves" not in s and s.get("evolves_from"):
        s = species[s["evolves_from"]]
    return [moves[e["move"]] for e in s.get("moves", [])]


if __name__ == "__main__":
    by_style = {}
    for sid, s in species.items():
        by_style.setdefault(s.get("style", "?"), []).append(sid)
    print(f"{'style':10} {'n':>3} {'hp':>6} {'dps L1':>7} {'dps L3':>7} {'reach':>6}")
    for style, ids in sorted(by_style.items()):
        hp = statistics.mean(species[i]["stats"]["hp"] * HP_MULT for i in ids)
        mains = [mains_of(i) for i in ids]
        d1 = statistics.mean(m[0]["power"] and move_dps(m[0]) for m in mains if m)
        d3 = statistics.mean(move_dps(m[-1]) for m in mains if m)
        r = statistics.mean(reach(m[0]) for m in mains if m)
        print(f"{style:10} {len(ids):3} {hp:6.0f} {d1:7.0f} {d3:7.0f} {r:6.1f}")
    print()
    all_dps = [move_dps(m) for m in moves.values() if m["slot"] == "main"]
    mean, sd = statistics.mean(all_dps), statistics.pstdev(all_dps)
    print(f"main attacks: {len(all_dps)}, mean dps {mean:.0f}, sd {sd:.0f}")
    for mid, m in sorted(moves.items()):
        if m["slot"] != "main":
            continue
        d = move_dps(m)
        if "--all" in sys.argv or abs(d - mean) > 2 * sd:
            print(f"  {mid:22} {m['kind']:10} dps {d:5.0f}  reach {reach(m):4.1f}")
