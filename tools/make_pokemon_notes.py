"""Writes docs/pokemon_notes.md: every playable line with its stages, types,
evolve levels, main attacks (and the level or TM that unlocks them), gadget,
supers, TM supers, HMs and how to unlock it. Built from the game's data files,
so rerun it after changing them:

    python3 tools/make_pokemon_notes.py
"""
import json, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
DATA = os.path.join(ROOT, "data")


def load(path):
    return json.load(open(os.path.join(DATA, path)))


def main():
    defs = {f[:-5]: load("brawlers/" + f) for f in os.listdir(os.path.join(DATA, "brawlers")) if f.endswith(".json")}
    moves = {}
    for f in os.listdir(os.path.join(DATA, "moves")):
        for k, v in load("moves/" + f).items():
            if not k.startswith("_"):
                moves[k] = v
    prog = load("progression.json")
    unlocks = load("unlocks.json")
    styles = load("styles.json")
    rules = load("rules.json")
    power_levels = rules["trainer"]["power_up_levels"]
    entry_of = {e["family"]: e for e in unlocks["order"]}

    def line_of(base):
        out, todo = [], [base]
        while todo:
            sid = todo.pop(0)
            out.append(sid)
            nxt = defs[sid].get("evolves_to", "")
            todo += nxt if isinstance(nxt, list) else ([nxt] if nxt else [])
        return out

    def how(base):
        if base in unlocks["starters"]:
            return "Starter (pick one at the start; the others unlock at trainer levels %s)" % ", ".join(map(str, unlocks["starter_levels"]))
        if base in unlocks["free"]:
            return "Free with your starter"
        e = entry_of.get(base, {})
        if "challenge" in e:
            return "Challenge: " + e["challenge"]["text"]
        if "trainer_level" in e:
            return "Trainer level %d (%s)" % (e["trainer_level"], e["area"])
        return "Found in Poké Balls (%s)" % e.get("area", "")

    bases = sorted([s for s, d in defs.items() if not d.get("evolves_from") and not d.get("legendary")], key=lambda s: defs[s]["dex"])
    out = ["# Pokémon notes", "",
           "Generated by `tools/make_pokemon_notes.py` from the game's data. Levels are your profile level for that line "
           "(Charmander's level covers Charmeleon and Charizard).", "",
           "- **Evolving:** 3 KOs in a match, or 2 once your line has reached the main-series evolve level.",
           "- **Lines that can't evolve further** Power Up instead: 3 KOs, or 2 from level %d (first) and %d (second)." % tuple(power_levels),
           "- **Main attacks:** the first is known from the start; the others unlock at the level shown, or right away with the TM.",
           "- **TM supers:** each stage can use the TM supers of its own types (two per type), shaped to its play style and a little weaker before the final evolution. **HMs** are taught one line at a time.", ""]
    for base in bases:
        line = line_of(base)
        d = defs[base]
        out.append("## #%03d %s line" % (d["dex"], " › ".join(defs[s]["name"] for s in line)))
        out.append("")
        out.append("- **How to unlock:** " + how(base))
        style = styles.get(d.get("style", ""), {})
        out.append("- **Play style:** %s (plays like %s)" % (style.get("label", d.get("style", "")), style.get("like", "")))
        stages = []
        for s in line:
            sd = defs[s]
            evo = ""
            if sd.get("evolves_to"):
                evo = " - evolves at Lv %d" % sd.get("evolve_level", 25)
            stages.append("%s (%s)%s" % (sd["name"], "/".join(t.capitalize() for t in sd["types"]), evo))
        out.append("- **Stages:** " + "; ".join(stages))
        mains = []
        for i, e in enumerate(d["moves"]):
            m = moves[e["move"]]
            when = "start" if i == 0 else "Lv %d" % e["level"]
            if e.get("tm"):
                when += " or " + prog["tms"][e["tm"]]["name"]
            mains.append("%s (%s, %s)" % (m["name"], m["type"].capitalize(), when))
        out.append("- **Main attacks:** " + "; ".join(mains))
        gadget = moves.get(d.get("gadget", ""), {})
        out.append("- **Gadget:** " + gadget.get("name", "-"))
        out.append("- **Supers:** " + "; ".join("%s: %s" % (defs[s]["name"], moves[defs[s]["super"]]["name"]) for s in line))
        by_stage = []
        for st in line:
            names = sorted(moves[t["super"]]["name"] for t in prog["tms"].values() if t.get("super") and moves[t["super"]]["type"] in defs[st]["types"])
            by_stage.append("%s: %s" % (defs[st]["name"], ", ".join(names) or "none"))
        out.append("- **TM supers** (by type, per stage): " + "; ".join(by_stage))
        out.append("- **HMs:** " + ", ".join(h.replace("_", " ").title() for h in prog["hms"].get(base, [])))
        out.append("")
    path = os.path.join(ROOT, "docs", "pokemon_notes.md")
    open(path, "w").write("\n".join(out))
    print("wrote", path, len(bases), "lines")


if __name__ == "__main__":
    main()
